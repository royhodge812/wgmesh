package main

import (
	"errors"
	"fmt"
	"sort"
	"strings"
)

// Peer is one mesh peer as returned by the coordinator's /register
// endpoint (slice S-A). Endpoint is empty until heartbeats land (slice
// S-D); the writer must tolerate that.
type Peer struct {
	Name       string `json:"name"`
	Pubkey     string `json:"pubkey"`
	MeshIP     string `json:"mesh_ip"`
	Endpoint   string `json:"endpoint"`
	AllowedIPs string `json:"allowed_ips"`
}

// Interface is the local node's [Interface] section of wg0.conf.
type Interface struct {
	PrivateKey string // base64 WireGuard private key (32 bytes)
	Address    string // mesh IP, e.g. "10.66.0.3" ("/24" is added by the writer)
	ListenPort int    // 51820 for the mesh (approved gate)
}

// RenderConfig renders a wg0.conf for the local node from its interface
// settings and the peer list returned by /register.
//
// Rules:
//
//   - The local node itself is excluded from [Peer] sections (the
//     coordinator returns every node, including the caller).
//   - AllowedIPs is always the peer's mesh IP as a /32.
//   - Endpoint is written only when the coordinator knows one; empty
//     endpoints are omitted, not written blank (slice S-D fills them in).
//   - Every peer gets PersistentKeepalive 25 so nodes behind NAT/CGNAT
//     keep the tunnel up.
//   - Output is sorted by peer mesh IP so re-renders are stable.
func RenderConfig(iface Interface, selfPubkey string, peers []Peer) (string, error) {
	if iface.PrivateKey == "" {
		return "", errors.New("interface private key is empty")
	}
	if iface.Address == "" {
		return "", errors.New("interface address is empty")
	}
	if iface.ListenPort <= 0 || iface.ListenPort > 65535 {
		return "", fmt.Errorf("invalid listen port %d", iface.ListenPort)
	}
	var b strings.Builder
	b.WriteString("# wgmesh node config — generated by wgmesh-agent. Do not edit by hand;\n")
	b.WriteString("# re-run `wgmesh-agent write-config` (or register) to regenerate.\n")
	b.WriteString("# The private key in this file must stay mode 0600. Never share or commit it.\n")
	b.WriteString("[Interface]\n")
	fmt.Fprintf(&b, "PrivateKey = %s\n", iface.PrivateKey)
	fmt.Fprintf(&b, "Address = %s/24\n", iface.Address)
	fmt.Fprintf(&b, "ListenPort = %d\n", iface.ListenPort)

	others := make([]Peer, 0, len(peers))
	for _, p := range peers {
		if p.Pubkey == selfPubkey || p.MeshIP == iface.Address {
			continue
		}
		if p.Pubkey == "" || p.MeshIP == "" {
			return "", fmt.Errorf("peer %q is missing pubkey or mesh IP", p.Name)
		}
		others = append(others, p)
	}
	sort.Slice(others, func(i, j int) bool { return others[i].MeshIP < others[j].MeshIP })
	for _, p := range others {
		b.WriteString("\n[Peer]\n")
		fmt.Fprintf(&b, "# %s\n", p.Name)
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		fmt.Fprintf(&b, "AllowedIPs = %s/32\n", p.MeshIP)
		if p.Endpoint != "" {
			fmt.Fprintf(&b, "Endpoint = %s\n", p.Endpoint)
		}
		b.WriteString("PersistentKeepalive = 25\n")
	}
	return b.String(), nil
}
